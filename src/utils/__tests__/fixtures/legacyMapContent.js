/**
 * A legacy-authored NetworkMapContent document as GET /v1/objects/{id}/map emits it:
 *   - one element of every MAP_ELEMENT_* type
 *   - element configs are JSON strings of the Gson-serialized config classes, enums by name
 *   - colors are BGR integers (red in the low byte)
 *   - the map-level key "defaultLinkWidht" matches the server's spelling
 *   - links have no "id" key - the WebAPI does not expose link ids
 *   - one dangling link that must survive a read-edit-save round trip unrendered
 */

