/**
 * PUT parses the legacy persistent-config keys ("TextBox", "DCIList"), not the keys GET emits.
 * Both variants are written, as serializeNetworkMapContent() does.
 */
export function toPutShape(content) {
  const put = {
    ...content,
    elements: (content.elements ?? []).map((el) => {
      const out = { ...el }
      if (el.type === 5 && el.config != null) out.TextBox = el.config
      if ((el.type === 3 || el.type === 4) && el.dciList != null) out.DCIList = el.dciList
      return out
    }),
    links: (content.links ?? []).map((l) => ({ ...l })),
  }
  // GET emits null for unset NXSL scripts; the PUT handler requires strings
  if (put.filter === null) put.filter = ''
  if (put.linkScript === null) put.linkScript = ''
  return put
}
